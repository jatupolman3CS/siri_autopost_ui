// Regenerates the i18n dictionary and seed data from the Claude Design handoff's autopost-data.js.
// Usage: node tools/import-design-data.mjs <path/to/autopost-data.js>
// The sample data is cut down to Facebook groups and pages (tools/facebook-only.mjs): the other social
// platforms of the design are a later phase. Dictionary wording that the system contradicts is corrected
// in src/app/core/i18n/i18n.fixes.ts, never here.
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';
import { facebookOnly } from './facebook-only.mjs';

const src = process.argv[2];
if (!src) throw new Error('usage: node tools/import-design-data.mjs <autopost-data.js>');
const window = {};
vm.runInNewContext(readFileSync(src, 'utf8'), { window });
const { AP_I18N } = window;
delete window.AP_SEED.contents; // derived from posts at runtime
const AP_SEED = facebookOnly(window.AP_SEED);

const header =
  '// Generated by tools/import-design-data.mjs from the design handoff. Do not edit by hand.\n';
writeFileSync(
  'src/app/core/i18n/i18n.data.ts',
  `${header}// Every leaf is a [th, en] pair.\nexport const AP_I18N = ${JSON.stringify(AP_I18N, null, 2)} as const;\n`,
);
writeFileSync(
  'src/app/core/data/seed.data.ts',
  `${header}// Sample data from the design (Facebook only, month and day names, plan limits, the landing-page preview).\nimport { SeedData } from './models';\n\nexport const SEED: SeedData = ${JSON.stringify(AP_SEED, null, 2)};\n`,
);
console.log('ok');
