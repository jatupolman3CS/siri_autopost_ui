// Regenerates the i18n dictionary from the Claude Design handoff's autopost-data.js.
// The handoff also carries sample data (accounts, posts, customers...); the app does not use it: every
// figure on screen comes from SIRIAUTOPOST.Api. Platform names and calendar names are in
// src/app/core/data/reference.ts (kept by hand).
// Usage: node tools/import-design-data.mjs <path/to/autopost-data.js>
import { readFileSync, writeFileSync } from 'node:fs';
import vm from 'node:vm';

const src = process.argv[2];
if (!src) throw new Error('usage: node tools/import-design-data.mjs <autopost-data.js>');
const window = {};
vm.runInNewContext(readFileSync(src, 'utf8'), { window });
const { AP_I18N } = window;

const header =
  '// Generated by tools/import-design-data.mjs from the design handoff. Do not edit by hand.\n';
writeFileSync(
  'src/app/core/i18n/i18n.data.ts',
  `${header}// Every leaf is a [th, en] pair.\nexport const AP_I18N = ${JSON.stringify(AP_I18N, null, 2)} as const;\n`,
);
console.log('ok');
